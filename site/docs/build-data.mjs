#!/usr/bin/env node
/**
 * Generates site/docs/site-data.js from the repository's REAL documentation,
 * so the static site renders the same source of truth the repo documents:
 *
 *   node site/docs/build-data.mjs
 *
 * Inputs (read-only):
 *   docs/features/*.md        feature articles
 *   CHANGELOG.md              release notes
 *
 * Output (committed artifact):
 *   site/docs/site-data.js    ES module exporting ARTICLES + CHANGELOG_MD
 *
 * The generated strings are JSON-encoded, which mechanically guarantees the
 * markdown lands byte-for-byte (backticks, quotes and newlines included).
 * Re-run this script whenever the upstream docs change and commit the result;
 * the recorded sha256 values make drift visible in review.
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..');
const featuresDir = path.join(repoRoot, 'docs', 'features');
const changelogPath = path.join(repoRoot, 'CHANGELOG.md');
const outPath = path.join(here, 'site-data.js');

function sha256(buf) {
  return createHash('sha256').update(buf).digest('hex');
}

/** First H1 title of a markdown document. */
function firstTitle(md) {
  const m = md.match(/^#\s+(.+?)\s*$/m);
  return m ? m[1].trim() : 'Untitled';
}

/** "Status: implementation in review." extracted from the leading notice quote. */
function firstStatus(md) {
  const m = md.match(/^>\s*(?:\*\*)?Status:?\*?\*?:?\s*(.+)$/im);
  if (!m) return '';
  return m[1].replace(/\*\*/g, '').replace(/\.$/, '').trim();
}

/** Plain-text summary: first paragraph of the Behavior section, inline markers stripped. */
function firstSummary(md) {
  const sec = md.match(/^##\s+Behavior\s*$([\s\S]*?)(?=^##\s|\s*$)/im);
  let para = '';
  if (sec) {
    para = sec[1].split(/\n\s*\n/).find((p) => p.trim() && !p.trim().startsWith('>')) || '';
  }
  if (!para) para = md.split(/\n\s*\n/).find((p) => p.trim() && !p.trim().startsWith('#')) || '';
  const text = para
    .replace(/`([^`]*)`/g, '$1')
    .replace(/\*\*([^*]*)\*\*/g, '$1')
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
  if (text.length <= 240) return text;
  const cut = text.slice(0, 240);
  return cut.slice(0, cut.lastIndexOf(' ')) + '…';
}

const files = fs
  .readdirSync(featuresDir)
  .filter((f) => f.endsWith('.md') && f !== 'README.md')
  .sort();

const articles = [];
const sources = [];
for (const f of files) {
  const abs = path.join(featuresDir, f);
  const buf = fs.readFileSync(abs);
  const md = buf.toString('utf8');
  sources.push({ path: `docs/features/${f}`, sha256: sha256(buf) });
  articles.push({
    id: f.replace(/\.md$/, ''),
    sourcePath: `docs/features/${f}`,
    title: firstTitle(md),
    status: firstStatus(md),
    summary: firstSummary(md),
    markdown: md,
  });
}

const clBuf = fs.readFileSync(changelogPath);
sources.push({ path: 'CHANGELOG.md', sha256: sha256(clBuf) });

const out = `// GENERATED FILE — do not hand-edit.
// Generated by site/docs/build-data.mjs from the repository's real documentation.
// Regenerate after changing docs/features/*.md or CHANGELOG.md:
//   node site/docs/build-data.mjs
// The sha256 entries in SOURCES make drift between this bundle and the
// canonical docs visible in code review.

export const DATA_VERSION = 1;

export const GENERATED_AT = ${JSON.stringify(new Date().toISOString())};

export const SOURCES = ${JSON.stringify(sources, null, 2)};

export const ARTICLES = ${JSON.stringify(articles, null, 2)};

export const CHANGELOG_MD = ${JSON.stringify(clBuf.toString('utf8'))};

export const CHANGELOG_SOURCE = ${JSON.stringify({
  path: 'CHANGELOG.md',
  sha256: sha256(clBuf),
})};
`;

fs.writeFileSync(outPath, out, 'utf8');
console.log(
  `[build-data] wrote ${path.relative(repoRoot, outPath)} (${out.length} bytes, ${articles.length} articles)`,
);
for (const s of sources) console.log(`  ${s.path}  ${s.sha256.slice(0, 12)}…`);
